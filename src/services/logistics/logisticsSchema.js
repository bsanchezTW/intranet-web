/**
 * Carga la plantilla inicial (la hoja «Check list diario») una sola vez.
 *
 * La marca «plantilla_sembrada» en logistics_settings la recuerda: si alguien
 * elimina todas las categorías, al reiniciar no vuelven. Las instalaciones
 * que ya tenían ítems reciben la marca sin sembrar nada.
 *
 * Antes, si lo único que hay es la plantilla provisoria (ningún ítem editado
 * o agregado) y nunca se registró un checklist, la retira para dejar la de
 * la hoja real.
 *
 * Va en una transacción con lock: dos procesos que arrancan a la vez no la
 * siembran dos veces.
 */
async function seedDefaultTemplate(countryCode = getCurrentCountry()) {
  const items = defaultTemplate(countryCode);
  const client = await db.getClient();
  try {
    await client.query("BEGIN");
    await client.query("SELECT pg_advisory_xact_lock(hashtext('vehicle_checklist_items'))");
    const { rowCount: provisorios } = await client.query(
      `DELETE FROM vehicle_checklist_items
        WHERE NOT EXISTS (SELECT 1 FROM vehicle_checklists)
          AND NOT EXISTS (
            SELECT 1 FROM vehicle_checklist_items i
             WHERE NOT (i.label = ANY($1::text[]))
          )`,
      [PROVISIONAL_TEMPLATE_LABELS],
    );
    if (provisorios) {
      // Sus categorías, si alcanzaron a crearse, se van con ellos, y la hoja
      // real se siembra en su lugar.
      await client.query(
        `DELETE FROM vehicle_checklist_categories c
          WHERE NOT EXISTS (SELECT 1 FROM vehicle_checklist_items i WHERE i.category_id = c.id)`,
      );
      await client.query("DELETE FROM logistics_settings WHERE key = 'plantilla_sembrada'");
    }
    await client.query(
      `INSERT INTO logistics_settings (key, value)
       SELECT 'plantilla_sembrada', 'existente'
        WHERE EXISTS (SELECT 1 FROM vehicle_checklist_items)
       ON CONFLICT (key) DO NOTHING`,
    );
    const { rowCount: sembrados } = await client.query(
      `INSERT INTO vehicle_checklist_items (category, label, critical, sort_order)
       SELECT s.category, s.label, s.critical, s.sort_order
         FROM UNNEST($1::text[], $2::text[], $3::boolean[], $4::int[])
              AS s(category, label, critical, sort_order)
        WHERE NOT EXISTS (SELECT 1 FROM logistics_settings WHERE key = 'plantilla_sembrada')`,
      [
        items.map((i) => i.category),
        items.map((i) => i.label),
        items.map((i) => i.critical),
        items.map((i) => i.sort_order),
      ],
    );
    if (sembrados) {
      await client.query(
        "INSERT INTO logistics_settings (key, value) VALUES ('plantilla_sembrada', 'hoja') ON CONFLICT (key) DO NOTHING",
      );
    }
    await client.query("COMMIT");
  } catch (err) {
    await client.query("ROLLBACK").catch(() => {});
    throw err;
  } finally {
    client.release();
  }
}

/**
 * Ítems sin categoría (plantillas de antes de las categorías, o la recién
 * sembrada): crea las que falten, en el orden del primer ítem de cada una, y
 * los enlaza. Sin parámetros, para ir en una sola consulta con lock.
 */
const SYNC_CATEGORIES = [
  `INSERT INTO vehicle_checklist_categories (name, sort_order)
   SELECT MIN(i.category), MIN(i.sort_order)
     FROM vehicle_checklist_items i
    WHERE i.category_id IS NULL
      AND NOT EXISTS (SELECT 1 FROM vehicle_checklist_categories c WHERE LOWER(c.name) = LOWER(i.category))
    GROUP BY LOWER(i.category)`,
  `UPDATE vehicle_checklist_items i
      SET category_id = c.id
     FROM vehicle_checklist_categories c
    WHERE i.category_id IS NULL AND LOWER(c.name) = LOWER(i.category)`,
];

async function ensureLogisticsSchema() {
  // Varios procesos arrancan a la vez: el lock los pone en fila (lockedDdl).
  await db.query(lockedDdl("logistica_schema", DDL_STATEMENTS));
  await seedDefaultTemplate();
  await db.query(lockedDdl("vehicle_checklist_categories", SYNC_CATEGORIES));
}

module.exports = { ensureLogisticsSchema, seedDefaultTemplate, DDL_STATEMENTS, SYNC_CATEGORIES };
