const db = require("../../db");
const { getCurrentCountry } = require("../../config/country");
const { defaultTemplate, PROVISIONAL_TEMPLATE_LABELS } = require("../../constants/vehicleChecklist");

/**
 * Schema de Logística, aplicado de forma idempotente al arrancar (mismo
 * patrón que billOfExchangeSchema.js: este archivo es la fuente canónica y
 * supabase/{chile,peru}/schema.sql lo documentan).
 *
 * logistics_vehicles es la flota: la usan el checklist y, después, las hojas
 * de ruta. Un checklist registrado es un documento de respaldo: congela la
 * patente, el conductor, quien lo firmó y el texto de cada ítem, para que no
 * cambie si mañana se edita el vehículo o la plantilla. No se edita ni se
 * borra; se anula con motivo.
 *
 * Numeración: correlativo por año (CV-00001-2026). UNIQUE sobre
 * (number_year, number_seq) es la última barrera; la primera es el advisory
 * lock de checklistService.
 */

