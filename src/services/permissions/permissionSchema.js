const db = require("../../db");

/**
 * Schema de Gestión de Permisos, idempotente al arrancar (mismo patrón que
 * costCenterSchema.js). Vive en la base de cada país: Chile y Perú
 * administran los suyos con el mismo catálogo (catalog/).
 *
 *   perm_sets          conjuntos con nombre ("Aprobador de rendiciones")
 *   perm_set_items     permisos de un conjunto, con su alcance
 *   perm_assignments   a quién (Global / Área / Jefes / Usuario) se le concede
 *                      o deniega un conjunto o un permiso suelto, con vigencia
 *   perm_audit         quién cambió qué, con el antes y el después
 *   perm_meta          versión de la configuración (invalida los cachés de
 *                      todos los procesos) y modo sombra / aplicar
 *
 * El superadmin es una marca en `users`, no un permiso: pasa todas las
 * comprobaciones y es el único que administra este módulo.
 */

const SCOPE_CHECK = `scope IS NULL OR scope IN ('propio', 'mi_area', 'a_cargo', 'areas', 'todo')`;

const DDL_STATEMENTS = [
  `ALTER TABLE users ADD COLUMN IF NOT EXISTS is_superadmin BOOLEAN NOT NULL DEFAULT FALSE`,

  `CREATE TABLE IF NOT EXISTS perm_sets (
    id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(60) NOT NULL UNIQUE,
    name        VARCHAR(120) NOT NULL,
    description TEXT,
    active      BOOLEAN NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
  )`,

  // Un permiso puede ir más de una vez en el conjunto con alcances distintos
  // (p. ej. "lo propio" + "las áreas Comercial y Logística").
  `CREATE TABLE IF NOT EXISTS perm_set_items (
    id                     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    set_id                 INTEGER NOT NULL REFERENCES perm_sets(id) ON DELETE CASCADE,
    permission_key         VARCHAR(120) NOT NULL,
    scope                  VARCHAR(10),
    scope_area_ids         INTEGER[] NOT NULL DEFAULT '{}',
    scope_include_subareas BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT perm_set_items_scope_check CHECK (${SCOPE_CHECK})
  )`,
  `CREATE UNIQUE INDEX IF NOT EXISTS perm_set_items_unique_idx
     ON perm_set_items (set_id, permission_key, COALESCE(scope, ''))`,

  // Concede o deniega un conjunto (set_id) o un permiso suelto
  // (permission_key + alcance). Una denegación quita el permiso entero: su
  // alcance no se usa.
  `CREATE TABLE IF NOT EXISTS perm_assignments (
    id                     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    principal_type         VARCHAR(10) NOT NULL,
    area_id                INTEGER REFERENCES work_areas(id) ON DELETE CASCADE,
    user_id                INTEGER REFERENCES users(id) ON DELETE CASCADE,
    include_subareas       BOOLEAN NOT NULL DEFAULT FALSE,
    set_id                 INTEGER REFERENCES perm_sets(id) ON DELETE CASCADE,
    permission_key         VARCHAR(120),
    scope                  VARCHAR(10),
    scope_area_ids         INTEGER[] NOT NULL DEFAULT '{}',
    scope_include_subareas BOOLEAN NOT NULL DEFAULT FALSE,
    effect                 VARCHAR(8) NOT NULL DEFAULT 'concede',
    valid_from             TIMESTAMPTZ,
    valid_until            TIMESTAMPTZ,
    note                   TEXT,
    granted_by             INTEGER REFERENCES users(id) ON DELETE SET NULL,
    created_at             TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT perm_assignments_principal_check
      CHECK (principal_type IN ('global', 'area', 'jefes', 'user')),
    CONSTRAINT perm_assignments_area_check
      CHECK (principal_type <> 'area' OR area_id IS NOT NULL),
    CONSTRAINT perm_assignments_user_check
      CHECK ((principal_type = 'user') = (user_id IS NOT NULL)),
    CONSTRAINT perm_assignments_target_check
      CHECK ((set_id IS NULL) <> (permission_key IS NULL)),
    CONSTRAINT perm_assignments_effect_check
      CHECK (effect IN ('concede', 'deniega')),
    CONSTRAINT perm_assignments_scope_check CHECK (${SCOPE_CHECK}),
    CONSTRAINT perm_assignments_validity_check
      CHECK (valid_until IS NULL OR valid_from IS NULL OR valid_until > valid_from)
  )`,
  `CREATE INDEX IF NOT EXISTS idx_perm_assignments_user
     ON perm_assignments (user_id) WHERE user_id IS NOT NULL`,
  `CREATE INDEX IF NOT EXISTS idx_perm_assignments_area
     ON perm_assignments (area_id) WHERE area_id IS NOT NULL`,
  `CREATE INDEX IF NOT EXISTS idx_perm_assignments_set
     ON perm_assignments (set_id) WHERE set_id IS NOT NULL`,

  `CREATE TABLE IF NOT EXISTS perm_audit (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at   TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    actor_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    action        VARCHAR(40) NOT NULL,
    entity_type   VARCHAR(20) NOT NULL,
    entity_id     INTEGER,
    old_value     JSONB,
    new_value     JSONB,
    note          TEXT
  )`,
  `CREATE INDEX IF NOT EXISTS idx_perm_audit_occurred
     ON perm_audit (occurred_at DESC)`,

  // Una sola fila. Cada escritura de permisos (o cambio de áreas y personas)
  // sube `version`; los procesos la consultan cada pocos segundos y recargan.
  `CREATE TABLE IF NOT EXISTS perm_meta (
    id              SMALLINT PRIMARY KEY DEFAULT 1,
    version         BIGINT NOT NULL DEFAULT 1,
    mode            VARCHAR(10) NOT NULL DEFAULT 'sombra',
    bootstrapped_at TIMESTAMPTZ,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT perm_meta_single_row CHECK (id = 1),
    CONSTRAINT perm_meta_mode_check CHECK (mode IN ('sombra', 'aplicar'))
  )`,
  `INSERT INTO perm_meta (id) VALUES (1) ON CONFLICT (id) DO NOTHING`,
];

async function ensurePermissionSchema() {
  const client = await db.getClient();
  try {
    await client.query(DDL_STATEMENTS.join(";\n"));
  } catch (err) {
    await client.query("ROLLBACK").catch(() => {});
    throw err;
  } finally {
    client.release();
  }
}

module.exports = {
  ensurePermissionSchema,
  DDL_STATEMENTS,
};
