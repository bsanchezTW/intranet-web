CREATE OR REPLACE FUNCTION chile.ensure_id_strategy()
RETURNS void
LANGUAGE plpgsql
AS $fn$
DECLARE
  p_schema constant text := 'chile';
  p_role constant text := 'intranet_chile';
  staging_offset constant bigint := 2000000000;
  six_digit_tables constant text[] := ARRAY[
    'users', 'vacation_requests', 'expense_requests'
  ];
  four_digit_tables constant text[] := ARRAY[
    'work_areas', 'support_tickets'
  ];
  identity_tables constant text[] := ARRAY[
    'news_articles', 'events', 'applications', 'courses', 'vacation_periods',
    'claude_conversations', 'vacation_balance_adjustments',
    'lunch_menu', 'public_holidays', 'documents', 'other_documents',
    'study_materials', 'event_photos', 'linkedin_posts', 'user_course_progress',
    'expense_request_items', 'expense_request_attachments', 'cost_centers'
  ];
  bigint_identity_tables constant text[] := ARRAY[
    'questions', 'question_options', 'change_log', 'claude_messages', 'ticket_replies'
  ];
  sequential_tables text[];
  t record;
  r record;
  rec record;
  fk record;
  tname text;
  candidate bigint;
  found_id bigint;
  i integer;
  seq_name text;
  max_id bigint;
  has_created_at boolean;
  table_ok boolean;
  ident text;
  order_sql text;
BEGIN
  sequential_tables := identity_tables || bigint_identity_tables;

  FOR t IN
    SELECT c.relname
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = p_schema AND c.relkind = 'r'
  LOOP
    EXECUTE format('LOCK TABLE %I.%I IN ACCESS EXCLUSIVE MODE', p_schema, t.relname);
  END LOOP;

  DROP TABLE IF EXISTS _id_map;
  DROP TABLE IF EXISTS _fk_backup;
  CREATE TEMP TABLE _id_map (
    table_name text NOT NULL,
    old_id bigint NOT NULL,
    new_id bigint NOT NULL,
    PRIMARY KEY (table_name, old_id),
    UNIQUE (table_name, new_id)
  ) ON COMMIT DROP;
  CREATE TEMP TABLE _fk_backup (
    table_name text NOT NULL,
    conname text NOT NULL,
    def text NOT NULL
  ) ON COMMIT DROP;

  INSERT INTO _fk_backup (table_name, conname, def)
  SELECT c.relname, con.conname, pg_get_constraintdef(con.oid)
  FROM pg_constraint con
  JOIN pg_class c ON c.oid = con.conrelid
  JOIN pg_namespace n ON n.oid = con.connamespace
  WHERE con.contype = 'f' AND n.nspname = p_schema;

  FOR fk IN SELECT * FROM _fk_backup LOOP
    EXECUTE format('ALTER TABLE %I.%I DROP CONSTRAINT %I', p_schema, fk.table_name, fk.conname);
  END LOOP;

  FOREACH tname IN ARRAY four_digit_tables LOOP
    SELECT EXISTS (
      SELECT 1 FROM pg_class c
      JOIN pg_namespace n ON n.oid = c.relnamespace
      WHERE n.nspname = p_schema AND c.relkind = 'r' AND c.relname = tname
    ) INTO table_ok;
    IF NOT table_ok THEN
      CONTINUE;
    END IF;

    FOR rec IN EXECUTE format(
      'SELECT id FROM %I.%I WHERE id < 1111 OR id > 9999 ORDER BY id',
      p_schema, tname
    ) LOOP
      FOR i IN 1..80 LOOP
        candidate := 1111 + floor(random() * 8889)::integer;
        found_id := NULL;
        EXECUTE format('SELECT 1 FROM %I.%I WHERE id = $1', p_schema, tname)
          INTO found_id
          USING candidate;
        EXIT WHEN found_id IS NULL
          AND NOT EXISTS (
            SELECT 1 FROM _id_map m
            WHERE m.table_name = tname AND m.new_id = candidate
          );
        IF i = 80 THEN
          RAISE EXCEPTION 'No fue posible generar un ID de 4 dígitos para %.%', p_schema, tname;
        END IF;
      END LOOP;
      INSERT INTO _id_map (table_name, old_id, new_id)
      VALUES (tname, rec.id, candidate);
    END LOOP;
  END LOOP;

  FOREACH tname IN ARRAY six_digit_tables LOOP
    SELECT EXISTS (
      SELECT 1 FROM pg_class c
      JOIN pg_namespace n ON n.oid = c.relnamespace
      WHERE n.nspname = p_schema AND c.relkind = 'r' AND c.relname = tname
    ) INTO table_ok;
    IF NOT table_ok THEN
      CONTINUE;
    END IF;

    FOR rec IN EXECUTE format(
      'SELECT id FROM %I.%I WHERE id < 100000 ORDER BY id',
      p_schema, tname
    ) LOOP
      FOR i IN 1..80 LOOP
        candidate := 100000 + floor(random() * 900000)::integer;
        found_id := NULL;
        EXECUTE format('SELECT 1 FROM %I.%I WHERE id = $1', p_schema, tname)
          INTO found_id
          USING candidate;
        EXIT WHEN found_id IS NULL
          AND NOT EXISTS (
            SELECT 1 FROM _id_map m
            WHERE m.table_name = tname AND m.new_id = candidate
          );
        IF i = 80 THEN
          RAISE EXCEPTION 'No fue posible generar un ID de 6 dígitos para %.%', p_schema, tname;
        END IF;
      END LOOP;
      INSERT INTO _id_map (table_name, old_id, new_id)
      VALUES (tname, rec.id, candidate);
    END LOOP;
  END LOOP;

  FOREACH tname IN ARRAY sequential_tables LOOP
    SELECT EXISTS (
      SELECT 1 FROM pg_class c
      JOIN pg_namespace n ON n.oid = c.relnamespace
      WHERE n.nspname = p_schema AND c.relkind = 'r' AND c.relname = tname
    ) INTO table_ok;
    IF NOT table_ok THEN
      CONTINUE;
    END IF;

    EXECUTE format('SELECT COALESCE(MAX(id), 0) FROM %I.%I', p_schema, tname) INTO max_id;
    IF max_id < 100000 THEN
      CONTINUE;
    END IF;

    SELECT EXISTS (
      SELECT 1 FROM information_schema.columns
      WHERE table_schema = p_schema AND table_name = tname AND column_name = 'created_at'
    ) INTO has_created_at;
    order_sql := CASE WHEN has_created_at THEN 'created_at, id' ELSE 'id' END;

    EXECUTE
      'INSERT INTO _id_map (table_name, old_id, new_id)
       SELECT $1, s.id, s.rn
       FROM (
         SELECT id, row_number() OVER (ORDER BY ' || order_sql || ')::bigint AS rn
         FROM ' || quote_ident(p_schema) || '.' || quote_ident(tname) || '
       ) s
       WHERE s.id IS DISTINCT FROM s.rn'
      USING tname;
  END LOOP;

  FOR r IN
    SELECT
      b.table_name AS child_table,
      (regexp_match(b.def, 'FOREIGN KEY \(([a-z0-9_]+)\)'))[1] AS fk_col,
      (regexp_match(b.def, 'REFERENCES (?:[a-z_]+\.)?([a-z0-9_]+)\(id\)'))[1] AS parent_table
    FROM _fk_backup b
  LOOP
    IF r.fk_col IS NULL OR r.parent_table IS NULL THEN
      CONTINUE;
    END IF;
    IF NOT EXISTS (
      SELECT 1 FROM _id_map m WHERE m.table_name = r.parent_table
    ) THEN
      CONTINUE;
    END IF;
    EXECUTE format(
      'UPDATE %I.%I t SET %I = m.new_id FROM _id_map m WHERE m.table_name = %L AND t.%I = m.old_id',
      p_schema, r.child_table, r.fk_col, r.parent_table, r.fk_col
    );
  END LOOP;

  IF EXISTS (
    SELECT 1
    FROM information_schema.columns
    WHERE table_schema = p_schema
      AND table_name = 'vacation_requests'
      AND column_name = 'period_allocations'
  ) THEN
    EXECUTE format(
      $q$
      UPDATE %I.vacation_requests vr
      SET period_allocations = sub.new_alloc
      FROM (
        SELECT vr2.id,
          jsonb_agg(
            CASE
              WHEN m.new_id IS NULL THEN elem
              ELSE jsonb_set(elem, '{periodId}', to_jsonb(m.new_id))
            END
            ORDER BY ordinality
          ) AS new_alloc
        FROM %I.vacation_requests vr2
        CROSS JOIN LATERAL jsonb_array_elements(vr2.period_allocations)
          WITH ORDINALITY AS x(elem, ordinality)
        LEFT JOIN _id_map m
          ON m.table_name = 'vacation_periods'
         AND m.old_id = NULLIF(elem->>'periodId', '')::bigint
        WHERE vr2.period_allocations IS NOT NULL
          AND jsonb_typeof(vr2.period_allocations) = 'array'
          AND jsonb_array_length(vr2.period_allocations) > 0
        GROUP BY vr2.id
      ) sub
      WHERE vr.id = sub.id
      $q$,
      p_schema, p_schema
    );
  END IF;

  IF EXISTS (
    SELECT 1 FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = p_schema AND c.relkind = 'r' AND c.relname = 'change_log'
  ) AND EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_schema = p_schema AND table_name = 'change_log' AND column_name = 'link_path'
  ) THEN
    EXECUTE format(
      $q$
      UPDATE %I.change_log cl
      SET link_path = regexp_replace(
        cl.link_path,
        '/(' || m.old_id::text || ')(/|\?|$)',
        '/' || m.new_id::text || '\2',
        'g'
      )
      FROM _id_map m
      WHERE m.table_name IN (
        'support_tickets', 'news_articles', 'courses', 'events',
        'applications', 'vacation_requests'
      )
        AND cl.link_path ~ ('/' || m.old_id::text || '(/|\?|$)')
      $q$,
      p_schema
    );
  END IF;

  FOR t IN SELECT DISTINCT table_name FROM _id_map LOOP
    EXECUTE format(
      'UPDATE %I.%I SET id = id + %s WHERE id IN (SELECT old_id FROM _id_map WHERE table_name = %L)',
      p_schema, t.table_name, staging_offset, t.table_name
    );
    EXECUTE format(
      'UPDATE %I.%I t SET id = m.new_id FROM _id_map m WHERE m.table_name = %L AND t.id = m.old_id + %s',
      p_schema, t.table_name, t.table_name, staging_offset
    );
  END LOOP;

  FOREACH tname IN ARRAY bigint_identity_tables LOOP
    SELECT EXISTS (
      SELECT 1 FROM pg_class c
      JOIN pg_namespace n ON n.oid = c.relnamespace
      WHERE n.nspname = p_schema AND c.relkind = 'r' AND c.relname = tname
    ) INTO table_ok;
    IF NOT table_ok THEN
      CONTINUE;
    END IF;

    BEGIN
      EXECUTE format('ALTER TABLE %I.%I ALTER COLUMN id DROP IDENTITY IF EXISTS', p_schema, tname);
    EXCEPTION
      WHEN undefined_object THEN
        NULL;
    END;
    BEGIN
      EXECUTE format('ALTER TABLE %I.%I ALTER COLUMN id DROP DEFAULT', p_schema, tname);
    EXCEPTION
      WHEN undefined_object THEN
        NULL;
    END;
    EXECUTE format(
      'ALTER TABLE %I.%I ALTER COLUMN id TYPE bigint USING id::bigint',
      p_schema, tname
    );
  END LOOP;

  FOR r IN
    SELECT
      b.table_name AS child_table,
      (regexp_match(b.def, 'FOREIGN KEY \(([a-z0-9_]+)\)'))[1] AS fk_col,
      (regexp_match(b.def, 'REFERENCES (?:[a-z_]+\.)?([a-z0-9_]+)\(id\)'))[1] AS parent_table
    FROM _fk_backup b
  LOOP
    IF r.fk_col IS NULL OR r.parent_table IS NULL THEN
      CONTINUE;
    END IF;
    IF NOT (r.parent_table = ANY (bigint_identity_tables)) THEN
      CONTINUE;
    END IF;
    EXECUTE format(
      'ALTER TABLE %I.%I ALTER COLUMN %I TYPE bigint USING %I::bigint',
      p_schema, r.child_table, r.fk_col, r.fk_col
    );
  END LOOP;

  FOR fk IN SELECT * FROM _fk_backup LOOP
    EXECUTE format(
      'ALTER TABLE %I.%I ADD CONSTRAINT %I %s',
      p_schema, fk.table_name, fk.conname, fk.def
    );
  END LOOP;

  FOR t IN
    SELECT c.relname
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    JOIN pg_index i ON i.indrelid = c.oid AND i.indisprimary
    JOIN pg_attribute a ON a.attrelid = c.oid AND a.attnum = ANY (i.indkey)
    WHERE n.nspname = p_schema AND c.relkind = 'r'
    GROUP BY c.relname
    HAVING count(*) = 1
       AND min(a.attname) = 'id'
       AND min(a.atttypid) IN ('integer'::regtype, 'bigint'::regtype)
  LOOP
    EXECUTE format('DROP TRIGGER IF EXISTS trg_six_digit_id ON %I.%I', p_schema, t.relname);
    EXECUTE format('DROP TRIGGER IF EXISTS trg_four_digit_id ON %I.%I', p_schema, t.relname);
  END LOOP;

  FOREACH tname IN ARRAY six_digit_tables LOOP
    SELECT EXISTS (
      SELECT 1 FROM pg_class c
      JOIN pg_namespace n ON n.oid = c.relnamespace
      WHERE n.nspname = p_schema AND c.relkind = 'r' AND c.relname = tname
    ) INTO table_ok;
    IF NOT table_ok THEN
      CONTINUE;
    END IF;

    seq_name := pg_get_serial_sequence(format('%I.%I', p_schema, tname), 'id');
    EXECUTE format('ALTER TABLE %I.%I ALTER COLUMN id DROP DEFAULT', p_schema, tname);
    BEGIN
      EXECUTE format('ALTER TABLE %I.%I ALTER COLUMN id DROP IDENTITY IF EXISTS', p_schema, tname);
    EXCEPTION
      WHEN undefined_object THEN
        NULL;
    END;
    IF seq_name IS NOT NULL THEN
      EXECUTE format('DROP SEQUENCE IF EXISTS %s', seq_name);
    END IF;

    EXECUTE format(
      'CREATE TRIGGER trg_six_digit_id BEFORE INSERT ON %I.%I FOR EACH ROW EXECUTE FUNCTION chile.assign_six_digit_id()',
      p_schema, tname
    );
  END LOOP;

  FOREACH tname IN ARRAY four_digit_tables LOOP
    SELECT EXISTS (
      SELECT 1 FROM pg_class c
      JOIN pg_namespace n ON n.oid = c.relnamespace
      WHERE n.nspname = p_schema AND c.relkind = 'r' AND c.relname = tname
    ) INTO table_ok;
    IF NOT table_ok THEN
      CONTINUE;
    END IF;

    seq_name := pg_get_serial_sequence(format('%I.%I', p_schema, tname), 'id');
    EXECUTE format('ALTER TABLE %I.%I ALTER COLUMN id DROP DEFAULT', p_schema, tname);
    BEGIN
      EXECUTE format('ALTER TABLE %I.%I ALTER COLUMN id DROP IDENTITY IF EXISTS', p_schema, tname);
    EXCEPTION
      WHEN undefined_object THEN
        NULL;
    END;
    IF seq_name IS NOT NULL THEN
      EXECUTE format('DROP SEQUENCE IF EXISTS %s', seq_name);
    END IF;

    EXECUTE format(
      'CREATE TRIGGER trg_four_digit_id BEFORE INSERT ON %I.%I FOR EACH ROW EXECUTE FUNCTION chile.assign_four_digit_id()',
      p_schema, tname
    );
  END LOOP;

  FOREACH tname IN ARRAY sequential_tables LOOP
    SELECT EXISTS (
      SELECT 1 FROM pg_class c
      JOIN pg_namespace n ON n.oid = c.relnamespace
      WHERE n.nspname = p_schema AND c.relkind = 'r' AND c.relname = tname
    ) INTO table_ok;
    IF NOT table_ok THEN
      CONTINUE;
    END IF;

    SELECT a.attidentity INTO ident
    FROM pg_attribute a
    JOIN pg_class c ON c.oid = a.attrelid
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = p_schema
      AND c.relname = tname
      AND a.attname = 'id'
      AND NOT a.attisdropped;

    IF ident IS NULL OR ident = '' THEN
      EXECUTE format('ALTER TABLE %I.%I ALTER COLUMN id DROP DEFAULT', p_schema, tname);
      EXECUTE format(
        'ALTER TABLE %I.%I ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY',
        p_schema, tname
      );
    END IF;

    seq_name := pg_get_serial_sequence(format('%I.%I', p_schema, tname), 'id');
    EXECUTE format('SELECT COALESCE(MAX(id), 0) FROM %I.%I', p_schema, tname) INTO max_id;
    IF seq_name IS NOT NULL THEN
      IF max_id < 1 THEN
        EXECUTE format('SELECT setval(%L::regclass, 1, false)', seq_name);
      ELSE
        EXECUTE format('SELECT setval(%L::regclass, %s, true)', seq_name, max_id);
      END IF;
    END IF;
  END LOOP;

  EXECUTE format(
    'GRANT USAGE, SELECT, UPDATE ON ALL SEQUENCES IN SCHEMA %I TO %I',
    p_schema, p_role
  );
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role') THEN
    EXECUTE format('GRANT ALL ON ALL SEQUENCES IN SCHEMA %I TO service_role', p_schema);
  END IF;
END;
$fn$;

CREATE OR REPLACE FUNCTION chile.ensure_six_digit_ids()
RETURNS void
LANGUAGE plpgsql
AS $fn$
BEGIN
  PERFORM chile.ensure_id_strategy();
END;
$fn$;

