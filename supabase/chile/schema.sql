DO $do$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint con
    JOIN pg_class c ON c.oid = con.conrelid
    JOIN pg_namespace n ON n.oid = con.connamespace
    WHERE con.conname = 'work_areas_manager_fk'
      AND c.relname = 'work_areas' AND n.nspname = 'chile'
  ) THEN
    ALTER TABLE chile.work_areas
      ADD CONSTRAINT work_areas_manager_fk
      FOREIGN KEY (manager_user_id) REFERENCES chile.users(id) ON DELETE SET NULL;
  END IF;
END
$do$;
