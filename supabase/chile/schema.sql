-- ===========================================================
-- CENTROS DE COSTO
-- Segunda agrupación de colaboradores, independiente del área: el área dice
-- quién aprueba (una sola por persona) y el centro de costo a qué bolsillo se
-- carga el gasto (hasta dos por persona).
-- ===========================================================
CREATE TABLE IF NOT EXISTS chile.cost_centers (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- El código es lo que cita contabilidad: es la clave natural.
  code character varying(30) NOT NULL,
  name character varying(150) NOT NULL,
  -- Un centro en desuso se desactiva, no se borra: las rendiciones históricas
  -- tienen que seguir apuntando a algo.
  active boolean NOT NULL DEFAULT true,
  created_at timestamp with time zone NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS cost_centers_code_unique_idx
  ON chile.cost_centers (UPPER(TRIM(code)));
CREATE INDEX IF NOT EXISTS idx_cost_centers_active
  ON chile.cost_centers (active) WHERE active = true;

-- El tope de dos centros por colaborador se aplica en la ruta
-- (services/costCenters/costCenterService.js), no aquí: expresarlo en SQL
-- exigiría un trigger, y el único camino de escritura es /RRHH/centros-costo.
CREATE TABLE IF NOT EXISTS chile.user_cost_centers (
  user_id integer NOT NULL REFERENCES chile.users(id) ON DELETE CASCADE,
  cost_center_id integer NOT NULL REFERENCES chile.cost_centers(id) ON DELETE CASCADE,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  PRIMARY KEY (user_id, cost_center_id)
);
CREATE INDEX IF NOT EXISTS idx_user_cost_centers_center
  ON chile.user_cost_centers (cost_center_id);

