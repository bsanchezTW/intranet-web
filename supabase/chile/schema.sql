-- ===========================================================
-- CENTRO DE GASTOS
-- Dos etapas: el jefe del área aprueba y después Finanzas.
-- ===========================================================
DO $do$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE t.typname = 'expense_request_kind' AND n.nspname = 'chile'
  ) THEN
    CREATE TYPE chile.expense_request_kind AS ENUM ('rendicion','fondos');
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE t.typname = 'expense_request_status' AND n.nspname = 'chile'
  ) THEN
    CREATE TYPE chile.expense_request_status AS ENUM
      ('pending','approved_manager','approved_finance','rejected','cancelled','draft');
  END IF;
END
$do$;
-- Bases creadas antes de los borradores.
ALTER TYPE chile.expense_request_status ADD VALUE IF NOT EXISTS 'draft';

CREATE TABLE IF NOT EXISTS chile.expense_requests (
  id integer PRIMARY KEY,                        -- 6 dígitos (trg_six_digit_id)
  kind chile.expense_request_kind NOT NULL,
  status chile.expense_request_status NOT NULL DEFAULT 'pending',
  user_id integer NOT NULL REFERENCES chile.users(id) ON DELETE CASCADE,
  -- Se congela al crear: si el colaborador cambia de área, la solicitud sigue
  -- perteneciendo al área que la aprobó.
  work_area_id integer REFERENCES chile.work_areas(id) ON DELETE SET NULL,
  title character varying(200) NOT NULL,
  description text,
  currency_code character varying(3) NOT NULL,
  -- Siempre recalculado en el servidor desde expense_request_items.
  total_amount numeric(14,2) NOT NULL DEFAULT 0,
  needed_by date,                                -- sólo kind = 'fondos'
  -- Aprobador esperado. NULL con status 'pending' significa que el solicitante
  -- ES el jefe del área: no puede autoaprobarse y lo resuelve un administrador.
  manager_user_id integer REFERENCES chile.users(id) ON DELETE SET NULL,
  manager_reviewed_by integer REFERENCES chile.users(id) ON DELETE SET NULL,
  manager_reviewed_at timestamp with time zone,
  manager_notes text,
  finance_reviewed_by integer REFERENCES chile.users(id) ON DELETE SET NULL,
  finance_reviewed_at timestamp with time zone,
  finance_notes text,
  rejected_stage character varying(10),          -- 'manager' | 'finance'
  -- Datos del solicitante congelados al enviar. Una rendición es un documento
  -- contable: si mañana se corrige un RUT o alguien cambia de área, lo que
  -- Finanzas ya aprobó no debe cambiar solo.
  requester_name character varying(200),
  requester_national_id character varying(20),
  requester_email character varying(150),
  requester_area_name character varying(150),
  -- Imputación. El FK sirve para filtrar y agrupar; el código y el nombre se
  -- congelan por la misma razón que los datos del solicitante.
  cost_center_id integer REFERENCES chile.cost_centers(id) ON DELETE SET NULL,
  cost_center_code character varying(30),
  cost_center_name character varying(150),
  -- Cuenta de destino congelada al enviar. El titular son los requester_*.
  bank_code character varying(3) REFERENCES chile.banks(code) ON UPDATE CASCADE,
  bank_name character varying(120),
  bank_account_type character varying(20),
  bank_account_number character varying(20),
  -- Encabezado de la planilla de rendición.
  fund_type character varying(10)
    CHECK (fund_type IS NULL OR fund_type IN ('fijo', 'rendir')),
  destination character varying(150),
  period_start date,
  period_end date,
  -- Fondo asignado (sólo rendiciones; NULL = sin fondo). A reintegrar se
  -- deriva: total_amount - assigned_amount.
  assigned_amount numeric(14,2)
    CHECK (assigned_amount IS NULL OR assigned_amount >= 0),
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_at timestamp with time zone NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_expense_requests_cost_center
