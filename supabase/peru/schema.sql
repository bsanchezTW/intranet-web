-- ===========================================================
-- CENTRO DE GASTOS
-- Dos etapas: el jefe del área aprueba y después Finanzas.
-- ===========================================================
DO $do$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE t.typname = 'expense_request_kind' AND n.nspname = 'peru'
  ) THEN
    CREATE TYPE peru.expense_request_kind AS ENUM ('rendicion','fondos');
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM pg_type t JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE t.typname = 'expense_request_status' AND n.nspname = 'peru'
  ) THEN
    CREATE TYPE peru.expense_request_status AS ENUM
      ('pending','approved_manager','approved_finance','rejected','cancelled','draft');
  END IF;
END
$do$;
-- Bases creadas antes de los borradores.
ALTER TYPE peru.expense_request_status ADD VALUE IF NOT EXISTS 'draft';

CREATE TABLE IF NOT EXISTS peru.expense_requests (
  id integer PRIMARY KEY,                        -- 8 dígitos (trg_eight_digit_id)
  kind peru.expense_request_kind NOT NULL,
  status peru.expense_request_status NOT NULL DEFAULT 'pending',
  -- Borrar al colaborador no borra sus solicitudes: quedan con la ficha
  -- congelada (requester_*) y user_id NULL.
  user_id integer REFERENCES peru.users(id) ON DELETE SET NULL,
  -- Se congela al crear: si el colaborador cambia de área, la solicitud sigue
  -- perteneciendo al área que la aprobó.
  work_area_id integer REFERENCES peru.work_areas(id) ON DELETE SET NULL,
  title character varying(200) NOT NULL,
  description text,
  currency_code character varying(3) NOT NULL,
  -- Siempre recalculado en el servidor desde expense_request_items.
  total_amount numeric(14,2) NOT NULL DEFAULT 0,
  needed_by date,                                -- sólo kind = 'fondos'
  -- Aprobador esperado. NULL con status 'pending' significa que el solicitante
  -- ES el jefe del área: no puede autoaprobarse y lo resuelve un administrador.
  manager_user_id integer REFERENCES peru.users(id) ON DELETE SET NULL,
  manager_reviewed_by integer REFERENCES peru.users(id) ON DELETE SET NULL,
  manager_reviewed_at timestamp with time zone,
  manager_notes text,
  finance_reviewed_by integer REFERENCES peru.users(id) ON DELETE SET NULL,
  finance_reviewed_at timestamp with time zone,
  finance_notes text,
  rejected_stage character varying(10),          -- 'manager' | 'finance'
  -- Datos del solicitante congelados al enviar. Una rendición es un documento
  -- contable: si mañana se corrige un RUT o alguien cambia de área, lo que
  -- Finanzas ya aprobó no debe cambiar solo.
  requester_name character varying(200),
  requester_national_id character varying(20),
  requester_email character varying(150),
  requester_area_name character varying(150),
  -- Imputación. El FK sirve para filtrar y agrupar; el código y el nombre se
  -- congelan por la misma razón que los datos del solicitante.
  cost_center_id integer REFERENCES peru.cost_centers(id) ON DELETE SET NULL,
  cost_center_code character varying(30),
  cost_center_name character varying(150),
  -- Cuenta de destino congelada al enviar. El titular son los requester_*.
  bank_code character varying(3) REFERENCES peru.banks(code) ON UPDATE CASCADE,
  bank_name character varying(120),
  bank_account_type character varying(20),
  bank_account_number character varying(20),
  -- Encabezado de la planilla de rendición.
  destination character varying(150),
  period_start date,
  period_end date,
  -- Fondo asignado: lo copia el sistema del total de la solicitud de fondos
  -- que se rinde (NULL = reembolso). Saldo = total_amount - assigned_amount.
  assigned_amount numeric(14,2)
    CHECK (assigned_amount IS NULL OR assigned_amount >= 0),
  -- Solicitud de fondos que esta rendición rinde (1:1). NULL = reembolso.
  -- NO ACTION: nada borra una solicitud de fondos enviada (ni borrar al usuario).
  fund_request_id integer REFERENCES peru.expense_requests(id),
  -- Liquidación: Finanzas confirma la devolución o el pago del saldo.
  settled_at timestamp with time zone,
  settled_by integer REFERENCES peru.users(id) ON DELETE SET NULL,
  settlement_notes text,
  CONSTRAINT expense_requests_fund_request_kind
    CHECK (fund_request_id IS NULL OR kind = 'rendicion'),
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  updated_at timestamp with time zone NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_expense_requests_cost_center
  ON peru.expense_requests (cost_center_id, status);
CREATE INDEX IF NOT EXISTS idx_expense_requests_user
  ON peru.expense_requests (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_expense_requests_status
  ON peru.expense_requests (status, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_expense_requests_area
  ON peru.expense_requests (work_area_id, status);
-- La bandeja del jefe es exactamente esta consulta.
CREATE INDEX IF NOT EXISTS idx_expense_requests_manager
  ON peru.expense_requests (manager_user_id, status)
  WHERE manager_user_id IS NOT NULL;
-- Borradores caducados (se eliminan a los 30 días sin cambios).
CREATE INDEX IF NOT EXISTS idx_expense_requests_drafts
  ON peru.expense_requests (updated_at)
  WHERE status = 'draft';
-- 1:1 fondo ↔ rendición: un fondo no puede tener dos rendiciones en curso o aprobadas.
CREATE UNIQUE INDEX IF NOT EXISTS expense_requests_fund_rendicion_unique
  ON peru.expense_requests (fund_request_id)
  WHERE kind = 'rendicion' AND status IN ('pending', 'approved_manager', 'approved_finance');
CREATE INDEX IF NOT EXISTS idx_expense_requests_fund
  ON peru.expense_requests (fund_request_id)
  WHERE fund_request_id IS NOT NULL;

