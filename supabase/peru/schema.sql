-- Schema Perú. Mismo núcleo que Chile, sin LinkedIn ni inscripciones a eventos.
-- El catálogo de Aplicaciones vive en shared.applications
-- (supabase/shared/schema.sql); peru.applications es una vista.

CREATE SCHEMA IF NOT EXISTS peru;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'intranet_peru') THEN
    CREATE ROLE intranet_peru LOGIN NOINHERIT;
  END IF;
END$$;

ALTER ROLE intranet_peru BYPASSRLS;
ALTER ROLE intranet_peru SET search_path = peru;

REVOKE ALL ON SCHEMA peru FROM PUBLIC;
GRANT USAGE, CREATE ON SCHEMA peru TO intranet_peru;

DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    REVOKE ALL ON SCHEMA peru FROM anon;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    REVOKE ALL ON SCHEMA peru FROM authenticated;
  END IF;
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'intranet_chile') THEN
    REVOKE ALL ON SCHEMA peru FROM intranet_chile;
  END IF;
END$$;

-- Enum vacaciones (por schema: el mismo typname en chile y peru no choca)
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_type t
    JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE t.typname = 'vacation_request_status'
      AND n.nspname = 'peru'
  ) THEN
    CREATE TYPE peru.vacation_request_status AS ENUM (
      'pending', 'approved', 'rejected', 'cancelled', 'in_progress', 'completed'
    );
  END IF;
END$$;

CREATE TABLE IF NOT EXISTS peru.work_areas (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  area_name character varying(150) NOT NULL,
  color character varying(7) NOT NULL DEFAULT '#5a6879',
  -- Jefe del área: primera aprobación del centro de gastos. La FK hacia users
  -- se agrega más abajo, porque esa tabla se crea después de esta.
  manager_user_id integer,
  CONSTRAINT work_areas_area_name_key UNIQUE (area_name),
  CONSTRAINT work_areas_color_hex CHECK (color ~ '^#[0-9A-Fa-f]{6}$')
);

CREATE TABLE IF NOT EXISTS peru.users (
  id integer PRIMARY KEY,
  first_name character varying(100),
  last_name character varying(100),
  email character varying(150),
  password_hash character varying(255),
  password_salt character varying(255),
  role character varying(50),
  email_confirmed boolean DEFAULT false,
  confirm_token character varying(255),
  confirm_expires timestamp without time zone,
  photo text,
  created_at timestamp without time zone DEFAULT now(),
  must_change_password boolean DEFAULT false,
  work_area_id integer REFERENCES peru.work_areas(id),
  birth_date date,
  is_intranet_user boolean NOT NULL DEFAULT true,
  -- Celular personal: lo ingresa la persona al registrarse o en su perfil.
  phone numeric,
  -- Contacto de empresa vs. personal: `email` es el corporativo (login) y
  -- `work_phone` el celular de la empresa. Sólo esos dos se muestran en el
  -- directorio y los entrega el asistente; los personales quedan ocultos.
  personal_email character varying(150),
  work_phone numeric,
  home_tutorial_seen boolean NOT NULL DEFAULT true,
  last_login_at timestamp with time zone,
  hire_date date,
  manager_user_id integer REFERENCES peru.users(id) ON DELETE SET NULL,
  prior_years_credited numeric(4,1) NOT NULL DEFAULT 0,
  progressive_days_override numeric(4,1),
  work_days_per_week smallint NOT NULL DEFAULT 5
    CHECK (work_days_per_week BETWEEN 3 AND 6),
  -- Documento de identidad: RUT en Chile, DNI en Perú. La forma la valida
  -- utils/nationalId.js según config/country.js. Admite NULL porque los
  -- colaboradores ya cargados no lo tienen; la rendición de gastos sí lo exige.
  national_id character varying(20),
  CONSTRAINT users_email_key UNIQUE (email)
);
-- Único parcial: dos personas no comparten documento, pero muchas lo tienen
-- vacío todavía.
CREATE UNIQUE INDEX IF NOT EXISTS users_national_id_unique_idx
  ON peru.users (national_id) WHERE national_id IS NOT NULL;

DO $do$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint con
    JOIN pg_class c ON c.oid = con.conrelid
    JOIN pg_namespace n ON n.oid = con.connamespace
    WHERE con.conname = 'work_areas_manager_fk'
      AND c.relname = 'work_areas' AND n.nspname = 'peru'
  ) THEN
    ALTER TABLE peru.work_areas
      ADD CONSTRAINT work_areas_manager_fk
      FOREIGN KEY (manager_user_id) REFERENCES peru.users(id) ON DELETE SET NULL;
  END IF;
END
$do$;
