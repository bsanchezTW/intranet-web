-- Correlativo 1, 2, 3… por ticket (no un identity global).
CREATE OR REPLACE FUNCTION peru.assign_ticket_reply_id()
RETURNS trigger
LANGUAGE plpgsql
AS $fn$
BEGIN
  IF NEW.ticket_id IS NULL THEN
    RAISE EXCEPTION 'ticket_id es obligatorio';
  END IF;
  PERFORM 1 FROM peru.support_tickets WHERE id = NEW.ticket_id FOR UPDATE;
  IF NEW.id IS NULL OR NEW.id <= 0 THEN
    SELECT COALESCE(MAX(id), 0) + 1
      INTO NEW.id
      FROM peru.ticket_replies
     WHERE ticket_id = NEW.ticket_id;
  END IF;
  RETURN NEW;
END;
