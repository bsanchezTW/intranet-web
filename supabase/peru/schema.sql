-- IDs: 6 dígitos aleatorios (100000-999999) en users y vacation_requests.
-- 8 dígitos aleatorios (10000000-99999999) en expense_requests (fondos y rendiciones).
-- 4 dígitos aleatorios (1111-9999) en work_areas y support_tickets.
-- integer IDENTITY en catálogo (noticias, eventos, apps, cursos, períodos,
-- documentos, feriados, menú, fotos, linkedin, progreso).
-- bigint IDENTITY en academy/quiz y logs (questions, question_options,
-- change_log). ticket_replies usa correlativo 1, 2, 3… por ticket.
-- ensure_id_strategy remapea filas existentes, propaga FKs/JSON/paths y deja
-- trigger o IDENTITY. No llamar en cada arranque de Node: toma ACCESS EXCLUSIVE
-- en todo el schema.

CREATE OR REPLACE FUNCTION peru.next_six_digit_id(p_table text)
RETURNS integer
LANGUAGE plpgsql
AS $fn$
DECLARE
  candidate integer;
  found_id integer;
  i integer;
BEGIN
  IF p_table IS NULL OR p_table !~ '^[a-z0-9_]+$' THEN
    RAISE EXCEPTION 'tabla inválida para ID de 6 dígitos';
  END IF;
  FOR i IN 1..80 LOOP
    candidate := 100000 + floor(random() * 900000)::integer;
    found_id := NULL;
    EXECUTE format('SELECT 1 FROM peru.%I WHERE id = $1', p_table)
      INTO found_id
      USING candidate;
    IF found_id IS NULL THEN
      RETURN candidate;
    END IF;
  END LOOP;
  RAISE EXCEPTION 'No fue posible generar un ID de 6 dígitos para peru.%', p_table;
END;
$fn$;

CREATE OR REPLACE FUNCTION peru.assign_six_digit_id()
RETURNS trigger
LANGUAGE plpgsql
AS $fn$
BEGIN
  IF NEW.id IS NULL OR NEW.id < 100000 THEN
    NEW.id := peru.next_six_digit_id(TG_TABLE_NAME);
  END IF;
  RETURN NEW;
END;
$fn$;

