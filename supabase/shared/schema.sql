-- Galería de eventos, compartida por Chile y Perú.
--
-- Un evento público se ve en las dos intranets. Uno privado solo en la del
-- país que lo creó (country_code). chile.events y peru.events filtran eso;
-- Home, el detalle y el asistente siguen leyendo `events`.
-- Las fotos quedan en el bucket del país que las sube: no se duplican.

CREATE TABLE IF NOT EXISTS shared.events (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name character varying(200) NOT NULL,
  slug character varying(200) NOT NULL UNIQUE,
  description text,
  image text,
  created_at timestamp without time zone DEFAULT now(),
  -- Columna histórica de Chile. El asistente la consulta; Perú no la tenía.
  fecha text,
  country_code character varying(2) NOT NULL CHECK (country_code IN ('CL', 'PE')),
  is_private boolean NOT NULL DEFAULT false
);

CREATE INDEX IF NOT EXISTS idx_events_country_private
  ON shared.events (country_code, is_private);

-- Copia lo que todavía viva en tablas de país. Los id nuevos no importan:
-- la URL es el slug y nadie referencia events.id. Si el slug choca, el de
-- Perú pasa a {slug}-pe y sus objetos del bucket intranet-content-pe se
-- renombran para no mezclar fotos con las de Chile.
DO $$
DECLARE
  rec record;
  new_slug text;
  suffix integer;
  image_value text;
  old_prefix text;
  new_prefix text;
BEGIN
  IF EXISTS (
    SELECT 1 FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'chile' AND c.relname = 'events' AND c.relkind = 'r'
  ) THEN
    IF EXISTS (
      SELECT 1 FROM information_schema.columns
      WHERE table_schema = 'chile' AND table_name = 'events' AND column_name = 'fecha'
    ) THEN
      INSERT INTO shared.events (
        name, slug, description, image, created_at, fecha, country_code, is_private
      )
      SELECT
        src.name, src.slug, src.description, src.image, src.created_at, src.fecha,
        'CL', false
      FROM chile.events src
      WHERE NOT EXISTS (
        SELECT 1 FROM shared.events dst WHERE dst.slug = src.slug
      );
    ELSE
      INSERT INTO shared.events (
        name, slug, description, image, created_at, fecha, country_code, is_private
      )
      SELECT
        src.name, src.slug, src.description, src.image, src.created_at, NULL,
        'CL', false
      FROM chile.events src
      WHERE NOT EXISTS (
        SELECT 1 FROM shared.events dst WHERE dst.slug = src.slug
      );
    END IF;
  END IF;

  IF EXISTS (
    SELECT 1 FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'peru' AND c.relname = 'events' AND c.relkind = 'r'
  ) THEN
    FOR rec IN SELECT * FROM peru.events ORDER BY id LOOP
      IF EXISTS (
        SELECT 1 FROM shared.events dst
        WHERE dst.country_code = 'PE'
          AND dst.name = rec.name
          AND dst.created_at IS NOT DISTINCT FROM rec.created_at
      ) THEN
        CONTINUE;
      END IF;

      new_slug := rec.slug;
      IF EXISTS (SELECT 1 FROM shared.events dst WHERE dst.slug = new_slug) THEN
        new_slug := rec.slug || '-pe';
        suffix := 2;
        WHILE EXISTS (SELECT 1 FROM shared.events dst WHERE dst.slug = new_slug) LOOP
          new_slug := rec.slug || '-pe-' || suffix;
          suffix := suffix + 1;
        END LOOP;
      END IF;

      image_value := rec.image;
      IF new_slug IS DISTINCT FROM rec.slug THEN
        old_prefix := 'eventos/' || rec.slug;
        new_prefix := 'eventos/' || new_slug;
        IF image_value IS NOT NULL THEN
          image_value := replace(image_value, old_prefix || '/', new_prefix || '/');
        END IF;

        IF to_regclass('storage.objects') IS NOT NULL THEN
          BEGIN
            UPDATE storage.objects
            SET name = new_prefix || substring(name FROM char_length(old_prefix) + 1)
            WHERE bucket_id = 'intranet-content-pe'
              AND (
                name = old_prefix
                OR left(name, char_length(old_prefix || '/')) = old_prefix || '/'
              );
          EXCEPTION
            WHEN insufficient_privilege OR undefined_table THEN
              RAISE NOTICE 'No se renombraron archivos de %: %', old_prefix, SQLERRM;
          END;
        END IF;
      END IF;

      INSERT INTO shared.events (
        name, slug, description, image, created_at, fecha, country_code, is_private
      )
      VALUES (
        rec.name, new_slug, rec.description, image_value, rec.created_at, NULL,
        'PE', false
      );
    END LOOP;
  END IF;
END$$;

